#!/usr/bin/env python3
"""Extract the sticker set from the Figma export into Android VectorDrawables.

Source: docs/design/stickers/status_stickers.svg, the "Project Status Stickers" sheet. It has two
panels with the same 40 designs; the left panel is the outlined ("die-cut") set that ships. Each
left-panel sticker is a <g clip-path> group whose clip rect is the sticker's bounding box.

Writes app/src/main/res/drawable/sticker_<name>.xml for each sticker. Names come from the
sticker's position in the 10 x 4 grid (reading order), not from the clip IDs, which are scrambled.

Only the SVG features this file uses are supported; anything else stops the script with an error
so that nothing is silently dropped.

Usage: python3 tools/stickers/extract_stickers.py [--debug-svg-dir DIR]
"""
import argparse
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "docs/design/stickers/status_stickers.svg"
OUTPUT = REPO / "app/src/main/res/drawable"

SVG_NS = "http://www.w3.org/2000/svg"
NS = {"svg": SVG_NS}

# Left (outlined) panel is x < 872 in the sheet; the right panel repeats the designs without outlines.
LEFT_PANEL_MAX_X = 872
ROWS, COLUMNS = 10, 4

# Reading order of the left panel. These names are the stable sticker IDs used by the app.
NAMES = [
    "thumbs_down", "high_alert", "super_star", "yeah",
    "great_idea", "plus_one", "yes", "wow_heart",
    "hate_it", "peace", "lift_off", "happy_star",
    "hot_flame", "dead", "flagged", "nope",
    "wow_burst", "sleepy", "hot_skull", "omg",
    "love_it", "ok_hand", "thumbs_up", "party_time",
    "fresh", "feedback", "meh", "hmm",
    "chill", "work_busy", "teary_star", "done",
    "ok_thumbs", "thanks", "good_idea", "lol",
    "awesome", "finished", "no", "almost_done",
]

NAMED_COLORS = {"white": "#FFFFFF", "black": "#000000"}
LINECAPS = {"butt": "butt", "round": "round", "square": "square"}
LINEJOINS = {"miter": "miter", "round": "round", "bevel": "bevel"}
SUPPORTED_PATH_ATTRS = {
    "d", "fill", "opacity", "stroke", "stroke-width",
    "stroke-linecap", "stroke-linejoin", "stroke-miterlimit", "fill-rule",
}

HEADER = (
    "<!-- Generated by tools/stickers/extract_stickers.py from "
    "docs/design/stickers/status_stickers.svg. Do not edit; re-run the script. -->"
)


def fail(message):
    sys.exit(f"error: {message}")


def color(value, where):
    value = value.strip()
    if value in NAMED_COLORS:
        return NAMED_COLORS[value]
    if value.startswith("#") and len(value) in (4, 7):
        if len(value) == 4:
            value = "#" + "".join(c * 2 for c in value[1:])
        return value.upper()
    fail(f"unsupported color {value!r} in {where}")


def number(value):
    return f"{float(value):g}"


def clip_rects(root):
    """Maps clip-path ID to (x, y, width, height)."""
    rects = {}
    for clip in root.find("svg:defs", NS).findall("svg:clipPath", NS):
        rect = clip.find("svg:rect", NS)
        if rect is None or len(clip) != 1:
            fail(f"clipPath {clip.get('id')} is not a single rect")
        transform = rect.get("transform", "")
        if not transform.startswith("translate(") or not transform.endswith(")"):
            fail(f"clipPath {clip.get('id')} has unsupported transform {transform!r}")
        x, y = (float(v) for v in transform[len("translate("):-1].replace(",", " ").split())
        rects[clip.get("id")] = (x, y, float(rect.get("width")), float(rect.get("height")))
    return rects


def left_panel_groups(root, rects):
    groups = []
    for group in root.findall("svg:g", NS):
        ref = group.get("clip-path", "")
        if not (ref.startswith("url(#") and ref.endswith(")")):
            fail(f"group without a clip-path: {group.attrib}")
        rect = rects[ref[len("url(#"):-1]]
        if rect[0] < LEFT_PANEL_MAX_X:
            groups.append((rect, group))
    if len(groups) != ROWS * COLUMNS:
        fail(f"expected {ROWS * COLUMNS} left-panel stickers, found {len(groups)}")
    return groups


def grid_order(groups):
    """Sorts groups into reading order: rows by vertical center, then columns by x."""
    by_center = sorted(groups, key=lambda item: item[0][1] + item[0][3] / 2)
    rows, current = [], [by_center[0]]
    for item in by_center[1:]:
        previous = current[-1][0]
        if (item[0][1] + item[0][3] / 2) - (previous[1] + previous[3] / 2) > 60:
            rows.append(current)
            current = []
        current.append(item)
    rows.append(current)
    if len(rows) != ROWS or any(len(row) != COLUMNS for row in rows):
        fail(f"expected a {ROWS}x{COLUMNS} grid, got rows of {[len(r) for r in rows]}")
    return [item for row in rows for item in sorted(row, key=lambda item: item[0][0])]


def path_element(path, where):
    unknown = set(path.attrib) - SUPPORTED_PATH_ATTRS
    if unknown:
        fail(f"unsupported path attributes {sorted(unknown)} in {where}")
    if len(path):
        fail(f"path with child elements in {where}")
    attrs = [("android:pathData", path.get("d"))]
    # The root <svg> sets fill="none", which paths inherit unless they set a fill.
    fill = path.get("fill", "none")
    stroke = path.get("stroke", "none")
    opacity = path.get("opacity")
    if fill != "none":
        attrs.append(("android:fillColor", color(fill, where)))
        if opacity is not None:
            attrs.append(("android:fillAlpha", number(opacity)))
        if path.get("fill-rule") == "evenodd":
            attrs.append(("android:fillType", "evenOdd"))
    if stroke != "none":
        attrs.append(("android:strokeColor", color(stroke, where)))
        attrs.append(("android:strokeWidth", number(path.get("stroke-width", "1"))))
        if opacity is not None:
            attrs.append(("android:strokeAlpha", number(opacity)))
        if "stroke-linecap" in path.attrib:
            attrs.append(("android:strokeLineCap", LINECAPS[path.get("stroke-linecap")]))
        if "stroke-linejoin" in path.attrib:
            attrs.append(("android:strokeLineJoin", LINEJOINS[path.get("stroke-linejoin")]))
        if "stroke-miterlimit" in path.attrib:
            attrs.append(("android:strokeMiterLimit", number(path.get("stroke-miterlimit"))))
    lines = "\n".join(f'            {name}="{value}"' for name, value in attrs)
    return f"        <path\n{lines} />"


def vector_drawable(rect, group, name):
    x, y, width, height = rect
    paths = []
    for child in group:
        if child.tag != f"{{{SVG_NS}}}path":
            fail(f"unsupported element {child.tag} in sticker {name}")
        paths.append(path_element(child, f"sticker {name}"))
    body = "\n".join(paths)
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"{HEADER}\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{number(width)}dp"\n'
        f'    android:height="{round(height, 2):g}dp"\n'
        f'    android:viewportWidth="{number(width)}"\n'
        f'    android:viewportHeight="{number(height)}">\n'
        f'    <group\n        android:translateX="{number(-x)}"\n        android:translateY="{number(-y)}">\n'
        f"{body}\n"
        "    </group>\n"
        "</vector>\n"
    )


def debug_svg(rect, group):
    x, y, width, height = rect
    inner = "".join(ET.tostring(child, encoding="unicode") for child in group)
    return (
        f'<svg xmlns="{SVG_NS}" width="{width * 4:g}" height="{height * 4:g}" '
        f'viewBox="{x:g} {y:g} {width:g} {height:g}" fill="none">'
        f'<rect x="{x:g}" y="{y:g}" width="{width:g}" height="{height:g}" fill="#0E0E0E"/>{inner}</svg>'
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--debug-svg-dir", type=Path, help="also write each sticker as a standalone SVG here")
    args = parser.parse_args()

    ET.register_namespace("", SVG_NS)
    root = ET.parse(SOURCE).getroot()
    if root.get("fill") != "none":
        fail("expected fill=\"none\" on the root <svg>")
    ordered = grid_order(left_panel_groups(root, clip_rects(root)))

    for old in OUTPUT.glob("sticker_*.xml"):
        old.unlink()
    if args.debug_svg_dir:
        args.debug_svg_dir.mkdir(parents=True, exist_ok=True)
    for name, (rect, group) in zip(NAMES, ordered):
        (OUTPUT / f"sticker_{name}.xml").write_text(vector_drawable(rect, group, name))
        if args.debug_svg_dir:
            (args.debug_svg_dir / f"{name}.svg").write_text(debug_svg(rect, group))
    print(f"wrote {len(ordered)} stickers to {OUTPUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
